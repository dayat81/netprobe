#!/usr/bin/env python3
"""Write web/maps-config.js from GOOGLE_MAPS_API_KEY (env or repo .env)."""
from __future__ import annotations

import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = Path(__file__).resolve().parent / "maps-config.js"


def _load_dotenv(path: Path) -> None:
    if not path.is_file():
        return
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, _, v = line.partition("=")
        k, v = k.strip(), v.strip().strip("'").strip('"')
        if k and k not in os.environ:
            os.environ[k] = v


def main() -> None:
    _load_dotenv(ROOT / ".env")
    key = (os.environ.get("GOOGLE_MAPS_API_KEY") or "").strip()
    if not key:
        raise SystemExit(
            "GOOGLE_MAPS_API_KEY not set (export it or put it in netprobe/.env)"
        )
    OUT.write_text(
        "// Generated by web/gen_maps_config.py — do not commit\n"
        f"window.GOOGLE_MAPS_API_KEY = {json.dumps(key)};\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT} ({len(key)} chars)")


if __name__ == "__main__":
    main()
